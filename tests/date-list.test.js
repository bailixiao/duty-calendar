// 「多個日期」（js/date-list.js）。執行：在專案根目錄執行 node --test
const test = require('node:test');
const assert = require('node:assert/strict');
const L = require('../js/date-list.js');

test('每週固定星期幾', () => {
  assert.deepEqual(L.weekly('2027-01-01', '2027-01-31', [3]), ['2027-01-06', '2027-01-13', '2027-01-20', '2027-01-27']);
  assert.deepEqual(L.weekly('2027-01-01', '2027-01-10', [0, 6]), ['2027-01-02', '2027-01-03', '2027-01-09', '2027-01-10']);
  assert.deepEqual(L.weekly('2027-01-10', '2027-01-01', [3]), []);
  assert.deepEqual(L.weekly('2027-01-01', '2027-01-31', []), []);
});

test('貼上日期清單：各種寫法、去重排序、看不懂的列出來', () => {
  const r = L.parse('1/7（四）、1/14\n2月4日, 2027/3/1 2027-03-08；116/4/5 1/7 13/40 abc', 2027);
  assert.deepEqual(r.dates, ['2027-01-07', '2027-01-14', '2027-02-04', '2027-03-01', '2027-03-08', '2027-04-05']);
  assert.deepEqual(r.bad, ['13/40', 'abc']);
  assert.deepEqual(L.parse('2/29', 2027).bad, ['2/29']); // 不存在的日期
  assert.deepEqual(L.parse('星期三 3/3', 2027).dates, ['2027-03-03']);
});

test('國定假日：固定節日、清明、春節除夕、端午中秋（農曆換算由外面給）', () => {
  // 測試用的農曆換算：只給 2027 年用到的幾天
  const table = { '2027-1-1': '2027-02-06', '2028-1-1': '2028-01-26', '2027-5-5': '2027-06-09', '2027-8-15': '2027-09-15' };
  const h = L.holidays(2027, (y, m, d) => table[`${y}-${m}-${d}`]);
  assert.equal(h['2027-01-01'], '元旦');
  assert.equal(h['2027-10-10'], '國慶日');
  assert.equal(h['2027-04-05'], '清明節');
  assert.equal(h['2027-02-05'], '除夕');
  assert.equal(h['2027-02-08'], '春節');
  assert.equal(h['2027-06-09'], '端午節');
  assert.equal(h['2027-09-15'], '中秋節');
  assert.equal(Object.values(h).filter((x) => x === '除夕').length, 1, '2028 年的除夕（2028/1/25）不算在 2027');
  assert.equal(L.holidays(2024)['2024-04-04'], '兒童節、清明節'); // 同一天
});

test('補假與連假：國定假日遇六日補假；連在一起 3 天以上，連假裡的六日也列出來', () => {
  // 2026：中秋 9/25（五）、教師節 9/28（一）→ 9/25～9/28 四天連假；國慶 10/10（六）→ 10/9（五）補假，10/9～10/11 連假
  const table = { '2026-1-1': '2026-02-17', '2027-1-1': '2027-02-06', '2025-1-1': '2025-01-29', '2026-5-5': '2026-06-19', '2026-8-15': '2026-09-25' };
  const off = L.offDays([2026], (y, m, d) => table[`${y}-${m}-${d}`]);
  assert.equal(off['2026-09-26'].kind, 'weekend');
  assert.match(off['2026-09-27'].name, /中秋節.*連假/);
  assert.equal(off['2026-09-28'].kind, 'holiday');
  assert.deepEqual([off['2026-10-09'].kind, off['2026-10-10'].kind, off['2026-10-11'].kind], ['makeup', 'holiday', 'weekend']);
  assert.equal(off['2026-10-09'].name, '國慶日補假');
  // 端午 6/19（五）→ 6/19～6/21 連假
  assert.equal(off['2026-06-20'].kind, 'weekend');
  // 普通週末不算
  assert.equal(off['2026-10-17'], undefined);
  // 勞動節 5/1（五）→ 5/2、5/3 也是連假
  assert.equal(off['2026-05-03'].kind, 'weekend');
});

test('固定的日子：每兩週、每三週、每月第幾個、每月最後一個、每月幾號', () => {
  // 2026/7/1 是星期三；那一週的星期六是 7/4
  assert.deepEqual(L.weekly('2026-07-01', '2026-08-31', [6], 'w2'), ['2026-07-04', '2026-07-18', '2026-08-01', '2026-08-15', '2026-08-29']);
  assert.deepEqual(L.weekly('2026-07-01', '2026-08-31', [6], 'w3'), ['2026-07-04', '2026-07-25', '2026-08-15']);
  assert.deepEqual(L.weekly('2026-07-01', '2026-09-30', [6], 'm1'), ['2026-07-04', '2026-08-01', '2026-09-05']);
  assert.deepEqual(L.weekly('2026-07-01', '2026-09-30', [0], 'm3'), ['2026-07-19', '2026-08-16', '2026-09-20']);
  assert.deepEqual(L.weekly('2026-07-01', '2026-09-30', [6], 'mL'), ['2026-07-25', '2026-08-29', '2026-09-26']);
  assert.deepEqual(L.weekly('2026-12-01', '2027-03-31', [], 'day', 30), ['2026-12-30', '2027-01-30', '2027-03-30']); // 2 月沒有 30 號
  assert.deepEqual(L.weekly('2026-07-01', '2026-07-31', [6]), ['2026-07-04', '2026-07-11', '2026-07-18', '2026-07-25']); // 沒給頻率＝每週
});
